const POR_CLAVE = Object.fromEntries(COMIDA.map(([k, , svg]) => [k, svg]))

export const esClaveIcono = (v) => !!POR_CLAVE[v]
export const svgDe = (v) => POR_CLAVE[v] ?? null

function Svg({ svg, size, className, style, ...resto }) {
  const lado = typeof size === 'number' ? `${size}px` : size
  return (
    <span aria-hidden="true" className={`icono inline-block shrink-0 ${className}`}
      style={{ width: lado, height: lado, ...style }} dangerouslySetInnerHTML={{ __html: svg }} {...resto} />
  )
}

export default function Icono({ n, size = 20, weight = 'duotone', className = '', ...resto }) {
  const svg = (weight !== 'duotone' && OTROS_PESOS[weight]?.[n]) || UI[n] || POR_CLAVE[n]
  if (!svg) return null
  return <Svg svg={svg} size={size} className={className} {...resto} />
}

// Ícono de categoría o logo: clave de la galería, o el emoji antiguo si aún no se cambió
export function IconoCategoria({ valor, size = 20, className = '' }) {
  const svg = POR_CLAVE[valor]
  if (svg) return <Svg svg={svg} size={size} className={className} />
  return <span className={className} style={{ fontSize: typeof size === 'number' ? size * 0.9 : size, lineHeight: 1 }} aria-hidden="true">{valor}</span>
}

// Selector de la galería (Ajustes → logo, Productos → categorías)
export function SelectorIcono({ valor, onCambio }) {
  return (
    <div className="grid grid-cols-6 gap-1.5">
      {COMIDA.map(([k, nombre, svg]) => (
        <button key={k} type="button" onClick={() => onCambio(k)} title={nombre} aria-label={nombre} aria-pressed={valor === k}
          className={`flex aspect-square items-center justify-center rounded-xl transition active:scale-90 ${
            valor === k ? 'bg-marca text-sobre-marca shadow' : 'bg-slate-100 text-slate-700'}`}>
          <Svg svg={svg} size={22} className="" />
        </button>
      ))}
    </div>
  )
}
